from __future__ import annotations

import json
import tempfile
import zipfile
from datetime import datetime
from pathlib import Path

import pandas as pd


def build_strategy_package(config: dict, weights_df: pd.DataFrame, output_path: str | Path) -> Path:
    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    run_config = _build_run_config(config)
    manifest = _build_manifest(config)
    with tempfile.TemporaryDirectory(prefix="strategy_package_") as tmp:
        package_dir = Path(tmp)
        weights_csv = package_dir / "weights.csv"
        weights_df.to_csv(weights_csv, index=False)
        weight_file = "weights.csv"
        try:
            weights_df.to_parquet(package_dir / "weights.parquet", index=False)
            weight_file = "weights.parquet"
        except Exception:
            weight_file = "weights.csv"
        run_config["weight_file"] = weight_file
        (package_dir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        (package_dir / "config.json").write_text(json.dumps(run_config, indent=2), encoding="utf-8")
        (package_dir / "README.md").write_text(_package_readme(config, weight_file), encoding="utf-8")
        with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            for path in sorted(package_dir.iterdir()):
                archive.write(path, arcname=path.name)
    return output


def _build_manifest(config: dict) -> dict:
    return {
        "package_version": str(config.get("package_version", "1.0")),
        "strategy_id": str(config["strategy_id"]),
        "strategy_name": str(config["strategy_name"]),
        "author": str(config.get("author", "researcher")),
        "mode": "weights",
        "created_at": datetime.now().isoformat(timespec="seconds"),
        "description": str(config.get("description", "")),
    }


def _build_run_config(config: dict) -> dict:
    run = dict(config["run"])
    run["mode"] = "weights"
    run["strategy_name"] = config["strategy_name"]
    return run


def _package_readme(config: dict, weight_file: str) -> str:
    return (
        f"# {config['strategy_name']}\n\n"
        "Generated by research_weights_template.\n\n"
        f"- mode: weights\n"
        f"- weight_file: {weight_file}\n"
        "- Upload endpoint: POST /backtests/run-package\n"
    )
