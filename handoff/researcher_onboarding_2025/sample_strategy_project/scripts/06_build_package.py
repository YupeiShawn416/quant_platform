from __future__ import annotations

import json
import sys
import tempfile
import zipfile
from datetime import datetime
from pathlib import Path

import pandas as pd

from common import load_config, project_path


def main() -> int:
    config = load_config()
    weights_path = project_path(config["output"]["weights_path"])
    if not weights_path.exists():
        print("找不到 weights 文件，请先运行 scripts/04_generate_weights.py。")
        return 1

    package_path = project_path(config["output"]["package_path"])
    package_path.parent.mkdir(parents=True, exist_ok=True)

    run_config = dict(config["run"])
    run_config["mode"] = "weights"
    run_config["weight_file"] = "weights.parquet"
    weights = pd.read_csv(weights_path)
    manifest = {
        "package_version": config["package_version"],
        "strategy_id": config["strategy_id"],
        "strategy_name": config["strategy_name"],
        "author": config.get("author", "researcher_name"),
        "mode": "weights",
        "created_at": datetime.now().isoformat(timespec="seconds"),
        "description": config.get("description", ""),
    }
    readme = (
        f"# {config['strategy_name']}\n\n"
        "This package was generated by the researcher onboarding sample project.\n"
        "It contains target weights only; no API token or raw market data is included.\n"
    )

    with tempfile.TemporaryDirectory() as tmpdir:
        tmp = Path(tmpdir)
        (tmp / "manifest.json").write_text(
            json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        (tmp / "config.json").write_text(
            json.dumps(run_config, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        (tmp / "README.md").write_text(readme, encoding="utf-8")
        weights.to_csv(tmp / "weights.csv", index=False)
        weights.to_parquet(tmp / "weights.parquet", index=False)

        with zipfile.ZipFile(package_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
            for file_path in sorted(tmp.iterdir()):
                zf.write(file_path, arcname=file_path.name)

    print(f"built package: {package_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
